/**
 * Generates db/02-seed.sql from the two CSVs.
 *
 * Run with `bun run seed:build`. The output is committed because the postgres
 * image reads it from /docker-entrypoint-initdb.d at first start, where no build
 * step is available.
 *
 * Emits COPY … FROM stdin rather than INSERT: it is the native bulk path, the
 * escaping rules are four characters instead of SQL string quoting, and each table
 * loads in one statement. Breweries are written before beers so the foreign key
 * resolves — the original script raced two async streams and got the order by luck.
 */

type Row = Record<string, string>;

const COPY_ESCAPES: Record<string, string> = {
  "\\": "\\\\",
  "\n": "\\n",
  "\r": "\\r",
  "\t": "\\t",
};

/** Escapes one field for PostgreSQL's COPY text format. */
const copyField = (value: string): string =>
  value.replace(/[\\\n\r\t]/g, (c) => COPY_ESCAPES[c] ?? c);

/** Reads a column, treating a missing one as empty rather than as undefined. */
const field = (row: Row, name: string): string => row[name] ?? "";

/**
 * Parses RFC 4180 CSV. Beer names contain commas and quotes, so splitting on ","
 * gives wrong answers on the name and style columns.
 */
const parseCsv = (text: string): Row[] => {
  const rows: string[][] = [];
  let row: string[] = [];
  let value = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          value += '"';
          i++;
        } else quoted = false;
      } else value += c;
      continue;
    }
    if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(value);
      value = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(value);
      value = "";
      rows.push(row);
      row = [];
    } else value += c;
  }
  if (value !== "" || row.length > 0) {
    row.push(value);
    rows.push(row);
  }

  const header = rows.shift();
  if (!header) return [];

  return rows
    .filter((r) => r.length === header.length)
    .map((r) =>
      Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? "").trim()]))
    );
};

/** Reads a CSV sitting next to this script. */
const readCsv = async (name: string): Promise<Row[]> =>
  parseCsv(await Bun.file(new URL(name, import.meta.url)).text());

/** Renders one COPY block for a table. */
const copyBlock = (
  table: string,
  columns: string[],
  rows: string[][]
): string =>
  `COPY ${table} (${columns.join(", ")}) FROM stdin;\n` +
  rows.map((r) => r.map(copyField).join("\t")).join("\n") +
  "\n\\.\n";

const breweries = await readCsv("breweries.csv");
const beers = await readCsv("beers.csv");

// abv is blank for 62 rows and ibu for 1005. The range filters treat a missing
// value as 0, so it is stored as 0 rather than NULL — see db/01-schema.sql.
const seed =
  "-- Generated by build/generate-seed.ts. Do not edit by hand.\n\n" +
  copyBlock(
    "breweries",
    ["id", "name", "city", "state"],
    breweries.map((b) => [
      field(b, "id"),
      field(b, "name"),
      field(b, "city"),
      field(b, "state"),
    ])
  ) +
  "\n" +
  copyBlock(
    "beers",
    ["id", "name", "style", "abv", "ibu", "ounces", "brewery_id"],
    beers.map((b) => [
      field(b, "id"),
      field(b, "name"),
      field(b, "style"),
      field(b, "abv") || "0",
      field(b, "ibu") || "0",
      field(b, "ounces"),
      field(b, "brewery_id"),
    ])
  );

await Bun.write(new URL("../db/02-seed.sql", import.meta.url), seed);

console.log(
  `wrote ${breweries.length} breweries and ${beers.length} beers to db/02-seed.sql`
);
